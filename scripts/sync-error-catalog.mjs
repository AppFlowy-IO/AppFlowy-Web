import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceIndex = args.indexOf('--source');
const target = resolve(root, 'src/application/errors/shared-error-catalog.json');
const manifestPath = resolve(root, 'src/application/errors/catalog-source.json');
const source = sourceIndex === -1 ? target : args[sourceIndex + 1];

if (!source || source.startsWith('--')) throw new Error('--source requires a catalog path');
const bytes = readFileSync(resolve(source));
const catalog = JSON.parse(bytes.toString());
const digest = createHash('sha256').update(bytes).digest('hex');
const fail = (message) => {
  throw new Error(message);
};

if (catalog.schema_version !== 1) fail('Unsupported error catalog schema');
for (const [reason, message] of Object.entries(catalog.reasons)) {
  if (!/^[A-Z0-9_]{1,64}$/.test(reason) || typeof message !== 'string' || !message.trim())
    fail(`Invalid reason: ${reason}`);
}
for (const [code, entry] of Object.entries(catalog.codes)) {
  if (!/^-?\d+$/.test(code) || !Number.isSafeInteger(Number(code))) fail(`Invalid Cloud code: ${code}`);
  if (Number(code) === 0 ? entry.reason !== null : !catalog.reasons[entry.reason]) fail(`Missing reason: ${code}`);
}
for (const section of ['http_codes', 'gotrue_codes', 'gotrue_legacy_messages']) {
  for (const reason of Object.values(catalog[section])) {
    if (!catalog.reasons[reason]) fail(`Missing ${section} reason: ${reason}`);
  }
}
if (!catalog.reasons[catalog.http_server_error_reason]) fail('Missing HTTP server-error reason');

const manifest = {
  source: 'AppFlowy-IO/AppFlowy-Premium/frontend/resources/error_messages/shared.json',
  sha256: digest,
};
const codes =
  '// Generated by scripts/sync-error-catalog.mjs. Do not edit.\n' +
  'export const serverErrorCodes = {\n' +
  Object.entries(catalog.codes)
    .map(([code, entry]) => `  ${entry.name}: ${code},`)
    .join('\n') +
  '\n} as const;\n';
const details = {
  withCode: 'Error {{code}}: {{message}}',
  publishNameTooLong: 'Keep the page address to {{max}} characters or fewer.',
};
const translationsPath = resolve(root, 'src/@types/translations/en.json');
const translations = JSON.parse(readFileSync(translationsPath, 'utf8'));
const codesPath = resolve(root, 'src/application/errors/shared-error-codes.ts');

if (check) {
  if (!readFileSync(target).equals(bytes)) fail('Web catalog differs from --source; sync the shared catalog');
  if (JSON.parse(readFileSync(manifestPath, 'utf8')).sha256 !== digest)
    fail('Catalog checksum changed; sync from the source');
  if (readFileSync(codesPath, 'utf8') !== codes) fail('Regenerate shared-error-codes.ts');
  if (JSON.stringify(translations.userError) !== JSON.stringify(catalog.reasons)) fail('Regenerate error translations');
  if (JSON.stringify(translations.userErrorDetail) !== JSON.stringify(details))
    fail('Regenerate error detail translations');
  console.log(
    `Shared error catalog verified (${Object.keys(catalog.codes).length} Cloud codes, sha256 ${digest.slice(0, 12)}).`
  );
} else {
  if (sourceIndex === -1) fail('Sync requires --source pointing to the canonical shared.json');
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, bytes);
  writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
  writeFileSync(codesPath, codes);
  translations.userError = catalog.reasons;
  translations.userErrorDetail = details;
  writeFileSync(translationsPath, JSON.stringify(translations, null, 2) + '\n');
  console.log('Synced the shared error catalog, Cloud code constants, and English translations.');
}
