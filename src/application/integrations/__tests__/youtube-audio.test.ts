import MockAdapter from 'axios-mock-adapter';

import { getAxios, initAPIService } from '@/application/services/js-services/http/core';

import { getYoutubeAudioMetadata, getYoutubeCaptions } from '../youtube-audio';
import { YoutubeAudioMetadata, YoutubeCaptionTranscript } from '../youtube-url';

jest.mock('@/application/session/token', () => ({
  getTokenParsed: () => ({ access_token: 'test-token', expires_at: Math.floor(Date.now() / 1000) + 3600 }), invalidToken: jest.fn(),
}));
jest.mock('@/application/services/js-services/http/gotrue', () => ({ initGrantService: jest.fn(), refreshToken: jest.fn() }));
jest.mock('@/utils/log', () => ({ Log: { debug: jest.fn(), warn: jest.fn(), error: jest.fn() } }));

const metadata: YoutubeAudioMetadata = { videoId: 'lr3hNhA0IfQ', title: 'Meeting: recording!', author: 'AppFlowy', duration: 754 };
const captions: YoutubeCaptionTranscript = {
  videoId: metadata.videoId, title: metadata.title, language: 'en', isAutoGenerated: false,
  segments: [{ text: 'Welcome to the meeting.', start: 1, end: 3 }],
};
const url = 'https://youtu.be/lr3hNhA0IfQ?si=share';

describe('YouTube browser captions bridge contract', () => {
  let http: MockAdapter;

  beforeAll(() => {
    initAPIService({ baseURL: 'https://cloud.example.test', gotrueURL: 'https://cloud.example.test/gotrue', wsURL: '' });
    http = new MockAdapter(getAxios()!);
  });
  afterEach(() => { http.reset(); jest.useRealTimers(); });
  afterAll(() => http.restore());

  it('fetches metadata from the local origin with the normal authenticated HTTP client', async () => {
    http.onGet('/api/youtube-audio').reply((config) => {
      expect(config.baseURL).toBe(window.location.origin);
      expect(config.params).toEqual({ workspace_id: 'workspace', url, action: 'metadata' });
      expect(config.headers?.Authorization).toBe('Bearer test-token');
      return [200, { code: 0, data: metadata }];
    });
    await expect(getYoutubeAudioMetadata('workspace', url, new AbortController().signal)).resolves.toEqual(metadata);
  });

  it('imports timed caption text by GET without downloading or posting media', async () => {
    http.onGet('/api/youtube-audio').reply((config) => {
      expect(config.baseURL).toBe(window.location.origin);
      expect(config.params).toEqual({ workspace_id: 'workspace', url, action: 'captions', language: 'en' });
      expect(config.headers?.Authorization).toBe('Bearer test-token');
      expect(config.responseType).not.toBe('blob');
      return [200, { code: 0, data: captions }];
    });
    await expect(getYoutubeCaptions('workspace', url, new AbortController().signal, 'en')).resolves.toEqual(captions);
    expect(http.history.get).toHaveLength(1);
    expect(http.history.post).toHaveLength(0);
  });

  it('omits the language parameter when the provider chooses the original captions', async () => {
    http.onGet('/api/youtube-audio').reply((config) => {
      expect(config.params).not.toHaveProperty('language');
      return [200, { code: 0, data: captions }];
    });
    await expect(getYoutubeCaptions('workspace', url, new AbortController().signal)).resolves.toEqual(captions);
  });

  it.each(['youtubeCaptionsUnavailable', 'youtubeCaptionsBlocked', 'youtubeCaptionsFailed'])('preserves the %s error from the caption provider', async (code) => {
    jest.useFakeTimers();
    http.onGet('/api/youtube-audio').reply(502, { code: 502, message: code });
    const result = expect(getYoutubeCaptions('workspace', url, new AbortController().signal)).rejects.toMatchObject({ code });

    await jest.advanceTimersByTimeAsync(8_000);
    await result;
  });

  it('rejects HTML from a server without the bridge', async () => {
    http.onGet('/api/youtube-audio').reply(200, '<html>AppFlowy</html>');
    await expect(getYoutubeCaptions('workspace', url, new AbortController().signal)).rejects.toMatchObject({ code: 'youtubeCaptionsFailed' });
  });

  it('reports empty captions without creating a media fallback request', async () => {
    http.onGet('/api/youtube-audio').reply(200, { code: 0, data: { ...captions, segments: [] } });
    await expect(getYoutubeCaptions('workspace', url, new AbortController().signal)).rejects.toMatchObject({ code: 'youtubeCaptionsUnavailable' });
    expect(http.history.post).toHaveLength(0);
  });

  it.each([
    { ...captions, videoId: 'another_vid' },
    { ...captions, segments: [{ text: 'Caption', start: -1, end: 3 }] },
    { ...captions, segments: [{ text: 'Caption', start: 5, end: 3 }] },
    { ...captions, segments: [{ text: ' ', start: 0, end: 3 }] },
  ])('rejects an invalid caption response before importing it (%j)', async (data) => {
    http.onGet('/api/youtube-audio').reply(200, { code: 0, data });
    await expect(getYoutubeCaptions('workspace', url, new AbortController().signal)).rejects.toMatchObject({ code: 'youtubeCaptionsFailed' });
  });

  it('does not begin an HTTP request after cancellation', async () => {
    const controller = new AbortController();

    controller.abort();
    await expect(getYoutubeCaptions('workspace', url, controller.signal)).rejects.toMatchObject({ name: 'AbortError' });
    expect(http.history.get).toHaveLength(0);
  });
});
