import { executeAPIRequest, getAxios } from '@/application/services/js-services/http/core';

import { AudioTranscriptionError, TranscriptionErrorCode } from './transcription-media';
import { isTranscriptionLimitError } from './transcription-usage';
import { YoutubeAudioMetadata, YoutubeCaptionTranscript, youtubeVideoId } from './youtube-url';

const API_PATH = '/api/youtube-audio';
const KNOWN_ERRORS: TranscriptionErrorCode[] = [
  'usageFailed', 'unsupportedUrl', 'quotaExceeded',
  'youtubeMetadataFailed', 'youtubeCaptionsUnavailable', 'youtubeCaptionsBlocked', 'youtubeCaptionsFailed',
];

function checkCancelled(signal: AbortSignal) {
  if (signal.aborted) throw new DOMException('Cancelled', 'AbortError');
}

function importError(error: unknown, fallback: 'youtubeMetadataFailed' | 'youtubeCaptionsFailed') {
  const detail = error as { code?: number; message?: string; diagnosticMessage?: string };

  if (isTranscriptionLimitError(detail)) return new AudioTranscriptionError('quotaExceeded', detail);
  const code = KNOWN_ERRORS.find((candidate) => candidate === (detail?.diagnosticMessage ?? detail?.message)) ?? fallback;

  return new AudioTranscriptionError(code, detail);
}

export async function getYoutubeAudioMetadata(workspaceId: string, url: string, signal: AbortSignal) {
  try {
    checkCancelled(signal);
    return await executeAPIRequest<YoutubeAudioMetadata>(
      () => getAxios()?.get(API_PATH, {
        baseURL: window.location.origin,
        params: { workspace_id: workspaceId, url, action: 'metadata' },
        signal, timeout: 35_000,
      }),
      { suppressResponseDataLogging: true }
    );
  } catch (error) {
    checkCancelled(signal);
    throw importError(error, 'youtubeMetadataFailed');
  }
}

/** Retrieve existing timed captions; no media download or transcription job is needed. */
export async function getYoutubeCaptions(
  workspaceId: string,
  url: string,
  signal: AbortSignal,
  language?: string
): Promise<YoutubeCaptionTranscript> {
  try {
    checkCancelled(signal);
    const transcript = await executeAPIRequest<YoutubeCaptionTranscript>(
      () => getAxios()?.get(API_PATH, {
        baseURL: window.location.origin,
        params: { workspace_id: workspaceId, url, action: 'captions', ...(language ? { language } : {}) },
        signal, timeout: 65_000,
      }),
      { suppressResponseDataLogging: true }
    );

    checkCancelled(signal);
    if (!transcript || transcript.videoId !== youtubeVideoId(url) || typeof transcript.title !== 'string' ||
      typeof transcript.language !== 'string' || typeof transcript.isAutoGenerated !== 'boolean' ||
      !Array.isArray(transcript.segments) || transcript.segments.some((segment) =>
        !segment || typeof segment.text !== 'string' || !segment.text.trim() ||
        !Number.isFinite(segment.start) || !Number.isFinite(segment.end) || segment.start < 0 || segment.end < segment.start
      )) throw new AudioTranscriptionError('youtubeCaptionsFailed');
    if (!transcript.segments.length) throw new AudioTranscriptionError('youtubeCaptionsUnavailable');
    return transcript;
  } catch (error) {
    checkCancelled(signal);
    if (error instanceof AudioTranscriptionError) throw error;
    throw importError(error, 'youtubeCaptionsFailed');
  }
}

/** Invoke from the click handler to retain the browser's clipboard activation. */
export function readTranscriptionClipboard(): Promise<string> {
  try {
    return navigator.clipboard?.readText().catch(() => '') ?? Promise.resolve('');
  } catch {
    return Promise.resolve('');
  }
}
