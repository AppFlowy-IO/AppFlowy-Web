import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';

import translations from '@/@types/translations/en.json';
import { AudioTranscriptionError } from '@/application/integrations/transcription-media';
import { getYoutubeCaptions, getYoutubeAudioMetadata } from '@/application/integrations/youtube-audio';
import { YoutubeAudioMetadata, YoutubeCaptionTranscript } from '@/application/integrations/youtube-url';

import { AIMeetingImportActions } from '../AIMeetingImport';
import { AIMeetingUrlDialog } from '../AIMeetingUrlDialog';
import { AIMeetingImportState } from '../useAIMeetingImport';

const mockT = (key: string, options?: Record<string, unknown>) => {
  const value = key.split('.').reduce<unknown>((current, part) => (current as Record<string, unknown>)?.[part], translations);

  return typeof value === 'string' ? value.replace(/{{(\w+)}}/g, (_match, name) => String(options?.[name] ?? '')) : key;
};

jest.mock('react-i18next', () => ({ useTranslation: () => ({ t: mockT }) }));
jest.mock('@/application/integrations/youtube-audio', () => ({
  ...jest.requireActual('@/application/integrations/youtube-audio'),
  getYoutubeAudioMetadata: jest.fn(), getYoutubeCaptions: jest.fn(),
}));

const metadata: YoutubeAudioMetadata = { videoId: 'lr3hNhA0IfQ', title: 'Meeting Recording', author: 'AppFlowy', duration: 754, thumbnailUrl: 'https://i.ytimg.com/vi/lr3hNhA0IfQ/hqdefault.jpg' };
const captions: YoutubeCaptionTranscript = {
  videoId: metadata.videoId, title: metadata.title, language: 'en', isAutoGenerated: false,
  segments: [{ text: 'Welcome to our meeting.', start: 1, end: 3 }],
};
const youtubeUrl = 'https://youtu.be/lr3hNhA0IfQ?si=share';
const mockMetadata = jest.mocked(getYoutubeAudioMetadata);
const mockCaptions = jest.mocked(getYoutubeCaptions);

beforeEach(() => {
  jest.resetAllMocks();
  Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: jest.fn().mockResolvedValue('') } });
  mockMetadata.mockResolvedValue(metadata);
  mockCaptions.mockResolvedValue(captions);
});
afterEach(cleanup);

function renderDialog(props: Partial<React.ComponentProps<typeof AIMeetingUrlDialog>> = {}) {
  const onClose = jest.fn();
  const onConfirm = jest.fn();
  const onConfirmCaptions = jest.fn();
  const result = render(<AIMeetingUrlDialog workspaceId='workspace' onClose={onClose} onConfirm={onConfirm} onConfirmCaptions={onConfirmCaptions} {...props} />);

  return { ...result, onClose, onConfirm, onConfirmCaptions };
}

async function pasteYoutube() {
  fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
  await screen.findByText('Meeting Recording');
}

describe('YouTube caption import dialog', () => {
  it('reads the clipboard once on the welcome button click and prefills its YouTube link', async () => {
    const readText = jest.fn().mockResolvedValue(youtubeUrl);

    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText } });
    const state = {
      workspaceId: 'workspace', available: true, busy: false, quotaExceeded: false,
      reportError: jest.fn(), importSource: jest.fn(), importCaptions: jest.fn(), dismissError: jest.fn(),
    } as unknown as AIMeetingImportState;

    render(<AIMeetingImportActions state={state} showWelcome />);
    fireEvent.click(screen.getByRole('button', { name: 'Paste YouTube URL' }));
    expect(readText).toHaveBeenCalledTimes(1);
    await screen.findByText('Meeting Recording');
    expect(screen.getByRole('textbox').value).toBe(youtubeUrl);
    expect(readText).toHaveBeenCalledTimes(1);
  });

  it('prefills any HTTP link without fetching metadata for an unsupported site', async () => {
    renderDialog({ clipboardText: Promise.resolve('https://example.com/page') });
    await waitFor(() => expect(screen.getByRole('textbox').value).toBe('https://example.com/page'));
    expect(mockMetadata).not.toHaveBeenCalled();
    expect(screen.getByRole('button', { name: 'Transcribe' }).disabled).toBe(true);
  });

  it('prefills a clipboard YouTube share link, loads its preview, and enables caption import', async () => {
    renderDialog({ clipboardText: Promise.resolve(` ${youtubeUrl} `) });
    await screen.findByText('Meeting Recording');
    expect(screen.getByRole('textbox').value).toBe(youtubeUrl);
    expect(screen.getByText('AppFlowy')).toBeTruthy();
    expect(screen.getByText('12:34')).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Import captions' }).disabled).toBe(false);
    expect(mockMetadata).toHaveBeenCalledWith('workspace', youtubeUrl, expect.any(AbortSignal));
  });

  it('keeps caption import disabled while loading video information', async () => {
    mockMetadata.mockReturnValue(new Promise(() => undefined));
    renderDialog();
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    expect((await screen.findByRole('status')).textContent).toContain('Loading video information');
    expect(screen.getByRole('button', { name: 'Import captions' }).disabled).toBe(true);
  });

  it.each([45, 14401, undefined])('allows caption import regardless of video duration (%s)', async (duration) => {
    mockMetadata.mockResolvedValue({ ...metadata, duration });
    const { onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    expect(screen.queryByRole('alert')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    await waitFor(() => expect(onConfirmCaptions).toHaveBeenCalledWith(captions));
  });

  it('shows a metadata error and retries the same link', async () => {
    mockMetadata.mockRejectedValueOnce(new AudioTranscriptionError('youtubeMetadataFailed'));
    renderDialog();
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    expect((await screen.findByRole('alert')).textContent).toContain("Couldn't load the YouTube video");
    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
    await screen.findByText('Meeting Recording');
    expect(mockMetadata).toHaveBeenCalledTimes(2);
  });

  it('reports an AppFlowy usage outage as transient and hides the upload fallback', async () => {
    mockMetadata.mockRejectedValueOnce(new AudioTranscriptionError('usageUnavailable', { httpStatus: 503, requestId: 'req-42' }));
    renderDialog({ onUpload: jest.fn() });
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    expect((await screen.findByRole('alert')).textContent).toContain("couldn't check your transcription allowance");
    expect(screen.queryByRole('button', { name: 'Download audio and transcribe' })).toBeNull();
    expect(screen.queryByRole('button', { name: 'Upload audio/video' })).toBeNull();
    expect(screen.getByText('Details').parentElement?.textContent).toContain('usageUnavailable · HTTP 503 · request req-42');
    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
    await screen.findByText('Meeting Recording');
    expect(mockMetadata).toHaveBeenCalledTimes(2);
  });

  it('explains an unavailable video without offering Retry while keeping upload available', async () => {
    mockMetadata.mockRejectedValueOnce(new AudioTranscriptionError('youtubeVideoUnavailable', { httpStatus: 404 }));
    const onUpload = jest.fn();

    renderDialog({ onUpload });
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    expect((await screen.findByRole('alert')).textContent).toContain("This video can't be imported");
    expect(screen.queryByRole('button', { name: 'Retry' })).toBeNull();
    expect(screen.queryByText('Details')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Upload audio/video' }));
    expect(onUpload).toHaveBeenCalledTimes(1);
    expect(mockMetadata).toHaveBeenCalledTimes(1);
  });

  it('names YouTube blocking at the metadata stage and shows details for bug reports', async () => {
    mockMetadata.mockRejectedValueOnce(new AudioTranscriptionError('youtubeBlocked', { httpStatus: 502, requestId: 'req-7' }));
    renderDialog();
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    expect((await screen.findByRole('alert')).textContent).toContain('YouTube is blocking requests');
    expect(screen.getByText('Details').parentElement?.textContent).toContain('youtubeBlocked · HTTP 502 · request req-7');
    expect(screen.getByRole('button', { name: 'Retry' })).toBeTruthy();
  });

  it('ignores an old preview after the user changes the link and preserves direct media transcription', async () => {
    let complete!: (value: YoutubeAudioMetadata) => void;

    mockMetadata.mockReturnValueOnce(new Promise((resolve) => { complete = resolve; }));
    const { onConfirm, onConfirmCaptions } = renderDialog();

    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    fireEvent.change(screen.getByRole('textbox'), { target: { value: 'https://example.com/meeting.mp3' } });
    await act(async () => complete(metadata));
    expect(screen.queryByText('Meeting Recording')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: 'Transcribe' }));
    expect(onConfirm).toHaveBeenCalledWith({ url: 'https://example.com/meeting.mp3' });
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    expect(mockCaptions).not.toHaveBeenCalled();
  });

  it('shows caption loading, prevents closing, and returns text without creating a media source', async () => {
    let complete!: (value: YoutubeCaptionTranscript) => void;

    mockCaptions.mockReturnValueOnce(new Promise((resolve) => { complete = resolve; }));
    const { onClose, onConfirm, onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    expect(screen.getByRole('status').textContent).toContain('Importing captions');
    expect(screen.queryByRole('progressbar')).toBeNull();
    expect(screen.getByRole('button', { name: 'Cancel' }).disabled).toBe(true);
    fireEvent.keyDown(screen.getByRole('dialog'), { key: 'Escape' });
    expect(onClose).not.toHaveBeenCalled();
    await act(async () => complete(captions));
    expect(onConfirmCaptions).toHaveBeenCalledTimes(1);
    expect(onConfirmCaptions).toHaveBeenCalledWith(captions);
    expect(onConfirm).not.toHaveBeenCalled();
  });

  it('stops an import, ignores its late completion, and permits a new request', async () => {
    let complete!: (value: YoutubeCaptionTranscript) => void;
    let signal!: AbortSignal;

    mockCaptions.mockImplementationOnce((_workspace, _url, active) => {
      signal = active;
      return new Promise((resolve) => { complete = resolve; });
    });
    const { onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    fireEvent.click(screen.getByRole('button', { name: 'Stop' }));
    expect(signal.aborted).toBe(true);
    expect(screen.getByRole('button', { name: 'Cancel' }).disabled).toBe(false);
    await act(async () => complete(captions));
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    await waitFor(() => expect(onConfirmCaptions).toHaveBeenCalledTimes(1));
    expect(mockCaptions).toHaveBeenCalledTimes(2);
  });

  it.each([
    ['youtubeCaptionsFailed', "Couldn't import the YouTube captions"],
    ['youtubeCaptionsBlocked', 'YouTube blocked access'],
  ] as const)('explains %s and allows a retry', async (code, message) => {
    mockCaptions.mockRejectedValueOnce(new AudioTranscriptionError(code));
    const { onClose, onConfirm, onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    expect((await screen.findByRole('alert')).textContent).toContain(message);
    expect(onConfirm).not.toHaveBeenCalled();
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    expect(onClose).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
    await waitFor(() => expect(onConfirmCaptions).toHaveBeenCalledWith(captions));
    expect(mockCaptions).toHaveBeenCalledTimes(2);
  });

  it('explains missing captions in the preview without starting transcription', async () => {
    mockMetadata.mockResolvedValue({ ...metadata, captionLanguages: [] });
    const { onConfirm } = renderDialog();

    await pasteYoutube();
    expect(screen.getByRole('alert').textContent).toContain('No captions are available');
    expect(screen.getByRole('alert').textContent).toContain('Upload the audio or video file');
    expect(screen.queryByRole('button', { name: 'Import captions' })).toBeNull();
    expect(mockCaptions).not.toHaveBeenCalled();
    expect(onConfirm).not.toHaveBeenCalled();
  });

  it('explains captions that become unavailable after the preview without downloading media', async () => {
    mockCaptions.mockRejectedValueOnce(new AudioTranscriptionError('youtubeCaptionsUnavailable'));
    const { onConfirm, onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    expect((await screen.findByRole('alert')).textContent).toContain('No captions are available');
    expect(screen.queryByRole('button', { name: 'Retry' })).toBeNull();
    expect(onConfirm).not.toHaveBeenCalled();
    expect(onConfirmCaptions).not.toHaveBeenCalled();
  });

  it('offers existing caption languages, prefers the selected transcript language, and imports the chosen track', async () => {
    mockMetadata.mockResolvedValue({
      ...metadata, captionLanguages: [
        { code: 'en', name: 'English (auto-generated)', isAutoGenerated: true },
        { code: 'es', name: 'Spanish', isAutoGenerated: true },
      ],
    });
    renderDialog({ language: 'es' });
    await pasteYoutube();
    expect(screen.getByRole('combobox', { name: 'Caption language' }).value).toBe('es');
    expect(screen.getByRole('option', { name: 'Spanish (Auto-generated)' })).toBeTruthy();
    expect(screen.getByRole('option', { name: 'English (auto-generated)' })).toBeTruthy();
    fireEvent.change(screen.getByRole('combobox'), { target: { value: 'en' } });
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    await waitFor(() => expect(mockCaptions).toHaveBeenCalledWith('workspace', youtubeUrl, expect.any(AbortSignal), 'en'));
  });

  it('aborts a pending caption request when the document is closed', async () => {
    let signal!: AbortSignal;

    mockCaptions.mockImplementation((_workspace, _url, active) => {
      signal = active;
      return new Promise(() => undefined);
    });
    const { unmount } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    unmount();
    expect(signal.aborted).toBe(true);
  });

  it('cancels the old workspace import and resets the dialog when switching workspaces', async () => {
    let complete!: (value: YoutubeCaptionTranscript) => void;
    let signal!: AbortSignal;

    mockCaptions.mockImplementationOnce((_workspace, _url, active) => {
      signal = active;
      return new Promise((resolve) => { complete = resolve; });
    });
    const { rerender, onClose, onConfirm, onConfirmCaptions } = renderDialog();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    rerender(<AIMeetingUrlDialog workspaceId='another-workspace' onClose={onClose} onConfirm={onConfirm} onConfirmCaptions={onConfirmCaptions} />);
    expect(signal.aborted).toBe(true);
    expect(screen.getByRole('textbox').value).toBe('');
    expect(screen.getByRole('button', { name: 'Cancel' }).disabled).toBe(false);
    await act(async () => complete(captions));
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    await pasteYoutube();
    expect(mockMetadata).toHaveBeenLastCalledWith('another-workspace', youtubeUrl, expect.any(AbortSignal));
  });

  it('uses the current confirmation handler when a caption request finishes after rerender', async () => {
    let complete!: (value: YoutubeCaptionTranscript) => void;

    mockCaptions.mockImplementationOnce(() => new Promise((resolve) => { complete = resolve; }));
    const { rerender, onClose, onConfirm, onConfirmCaptions } = renderDialog();
    const nextConfirm = jest.fn();

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    rerender(<AIMeetingUrlDialog workspaceId='workspace' onClose={onClose} onConfirm={onConfirm} onConfirmCaptions={nextConfirm} />);
    await act(async () => complete(captions));
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    expect(nextConfirm).toHaveBeenCalledWith(captions);
    expect(mockCaptions).toHaveBeenCalledTimes(1);
  });
});

describe('YouTube manual upload fallback', () => {
  it('offers manual upload when captions are missing without download or extension actions', async () => {
    mockMetadata.mockResolvedValue({ ...metadata, captionLanguages: [] });
    const onUpload = jest.fn();
    const { onConfirm, onConfirmCaptions } = renderDialog({ onUpload });

    await pasteYoutube();
    expect(screen.getByText('Upload an audio or video file from your device to transcribe it.')).toBeTruthy();
    expect(screen.getByRole('button', { name: 'Upload audio/video' }).disabled).toBe(false);
    expect(screen.queryByRole('button', { name: /download|extension/i })).toBeNull();
    expect(screen.queryByRole('link', { name: /download|extension/i })).toBeNull();
    expect(screen.queryByRole('status')).toBeNull();
    expect(onUpload).not.toHaveBeenCalled();
    expect(onConfirm).not.toHaveBeenCalled();
    expect(onConfirmCaptions).not.toHaveBeenCalled();
    expect(mockCaptions).not.toHaveBeenCalled();
    fireEvent.click(screen.getByRole('button', { name: 'Upload audio/video' }));
    expect(onUpload).toHaveBeenCalledTimes(1);
  });

  it('offers upload even when YouTube metadata cannot be fetched', async () => {
    mockMetadata.mockRejectedValueOnce(new AudioTranscriptionError('youtubeBlocked'));
    const onUpload = jest.fn();

    renderDialog({ onUpload });
    fireEvent.change(screen.getByRole('textbox'), { target: { value: youtubeUrl } });
    await screen.findByRole('button', { name: 'Upload audio/video' });
    fireEvent.click(screen.getByRole('button', { name: 'Upload audio/video' }));
    expect(onUpload).toHaveBeenCalledTimes(1);
  });

  it('opens the existing file picker from the fallback and transcribes the selected video', async () => {
    mockMetadata.mockResolvedValue({ ...metadata, captionLanguages: [] });
    Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { readText: jest.fn().mockResolvedValue(youtubeUrl) } });
    const state = {
      workspaceId: 'workspace', available: true, busy: false, quotaExceeded: false,
      reportError: jest.fn(), importSource: jest.fn(), importCaptions: jest.fn(), dismissError: jest.fn(),
    } as unknown as AIMeetingImportState;
    const { container } = render(<AIMeetingImportActions state={state} showWelcome />);
    const input = container.querySelector('input[type=file]') as HTMLInputElement;
    const click = jest.spyOn(input, 'click').mockImplementation(() => undefined);

    fireEvent.click(screen.getByRole('button', { name: 'Paste YouTube URL' }));
    await screen.findByRole('button', { name: 'Upload audio/video' });
    fireEvent.click(screen.getByRole('button', { name: 'Upload audio/video' }));
    expect(click).toHaveBeenCalledTimes(1);
    expect(screen.queryByRole('dialog')).toBeNull();
    const video = new File(['video'], 'meeting.mp4', { type: 'video/mp4' });

    fireEvent.change(input, { target: { files: [video] } });
    expect(state.importSource).toHaveBeenCalledWith(video);
    click.mockRestore();
  });

  it('disables upload when transcription allowance is exhausted while keeping caption retry available', async () => {
    mockCaptions.mockRejectedValueOnce(new AudioTranscriptionError('youtubeCaptionsBlocked'));
    const onUpload = jest.fn();
    const { onConfirmCaptions } = renderDialog({ mediaDisabled: true, onUpload });

    await pasteYoutube();
    fireEvent.click(screen.getByRole('button', { name: 'Import captions' }));
    await screen.findByRole('button', { name: 'Upload audio/video' });
    expect(screen.getByRole('button', { name: 'Upload audio/video' }).disabled).toBe(true);
    fireEvent.click(screen.getByRole('button', { name: 'Upload audio/video' }));
    expect(onUpload).not.toHaveBeenCalled();
    expect(screen.getByRole('button', { name: 'Import captions' }).disabled).toBe(false);
    fireEvent.click(screen.getByRole('button', { name: 'Retry' }));
    await waitFor(() => expect(onConfirmCaptions).toHaveBeenCalledWith(captions));
    expect(mockCaptions).toHaveBeenCalledTimes(2);
  });
});
